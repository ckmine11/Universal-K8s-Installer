// Regenerates src/theme-vars.css and src/theme-solid.css (run from frontend/):
//   node scripts/gen-theme.cjs src/theme-vars.css /dev/null src/theme-solid.css
const colors = require(process.cwd() + '/node_modules/tailwindcss/colors')
const iris = { 50:'#f3f1ff',100:'#e8e4ff',200:'#d4ccff',300:'#b6a8ff',400:'#9a87ff',500:'#8069fb',600:'#6b4ff0',700:'#5a3ed6',800:'#4932ad',900:'#3c2b88',950:'#221852' }
const graphite = { 50:'#f7f8f8',100:'#eeeff1',200:'#d6d8dc',300:'#b6b9bf',400:'#8f949c',500:'#71757d',600:'#4f5258',700:'#36383d',800:'#232428',900:'#151619',950:'#0c0d0f' }
const pal = { blue: iris, slate: graphite, emerald: colors.emerald, amber: colors.amber, red: colors.red, sky: colors.sky, purple: colors.purple, violet: colors.violet, rose: colors.rose, gray: colors.gray, cyan: colors.cyan, fuchsia: colors.fuchsia, orange: colors.orange, yellow: colors.yellow, green: colors.green, indigo: colors.indigo, pink: colors.pink, teal: colors.teal, lime: colors.lime }
const rgb = h => { h = h.replace('#',''); if (h.length===3) h=[...h].map(c=>c+c).join(''); return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16)).join(' ') }
const shades = [50,100,200,300,400,500,600,700,800,900,950]
const flip = s => ({50:950,100:900,200:800,300:700,400:600,500:500,600:400,700:300,800:200,900:100,950:50})[s]
let dark = '', light = ''
for (const [n,p] of Object.entries(pal)) for (const s of shades) { dark += `--c-${n}-${s}:${rgb(p[s])};`; light += `--c-${n}-${s}:${rgb(p[flip(s)])};` }
dark += '--c-white:255 255 255;--c-black:0 0 0;'
light += '--c-white:12 13 15;--c-black:255 255 255;'
const fs = require('fs')
fs.writeFileSync(process.argv[2], `/* generated by gen-theme: every palette shade as a variable; light flips the scale (50<->950 ... 500 stays) */\n:root,.kz-dark{${dark}}\n:root[data-theme="light"]{${light}}\n`)
fs.writeFileSync(process.argv[3], JSON.stringify(Object.fromEntries(Object.keys(pal).map(n => [n, Object.fromEntries(shades.map(s => [s, `rgb(var(--c-${n}-${s}) / <alpha-value>)`]))]))))
console.log(Object.keys(pal).length, 'palettes')

// ── light mode: solid accent buttons keep their real colour and white text ──
const SOLID = ['blue','emerald','red','amber','sky','violet','purple','rose','green','indigo','cyan','fuchsia','orange','pink','teal']
const solidShades = [500, 600, 700]
const tok = (pfx, n, s) => `[class~="${pfx}-${n}-${s}"]`
let pin = '', sel = []
for (const n of SOLID) for (const s of solidShades) {
    pin += `${tok('bg', n, s)}{background-color:rgb(${rgb(pal[n][s])})}`
    pin += `${tok('from', n, s)}{--tw-gradient-from:rgb(${rgb(pal[n][s])}) var(--tw-gradient-from-position);--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to)}`
    pin += `${tok('to', n, s)}{--tw-gradient-to:rgb(${rgb(pal[n][s])}) var(--tw-gradient-to-position)}`
    sel.push(tok('bg', n, s), tok('from', n, s))
}
sel.push('[class~="bg-[#8069fb]"]', '.kz-btn-primary')
const list = `:is(${sel.join(',')})`
const out = `/* generated: in light mode solid accent fills keep their real colour, and text on them stays white */\n` +
  pin.split('}').filter(Boolean).map(r => `:root[data-theme="light"] ${r}}`).join('\n') + '\n' +
  `:root[data-theme="light"] ${list}.text-white,:root[data-theme="light"] ${list} .text-white{color:#fff}\n`
require('fs').writeFileSync(process.argv[4], out)
console.log('solid rules', SOLID.length * solidShades.length)
